"""Plot end to end (python3 test/t_plot.py; needs Playwright with Chromium). Serves the folder on localhost and checks: a first note,
checklists (Enter for the next line, Backspace joins, ticked lines fold away), pin, colour, tags, folders (new, move a note, rename,
delete), search, delete and Undo, Recently deleted and Put back, Cards (Take a note, ticking on the card, the pop-up), the Board
(double-click adds a note typed in place, dragging keeps its place, a dot dragged onto another note joins them, a frame carries its
notes, zoom), Today (unticked lines carried over), back-up and restore, everything still there after a reload and when offline, a second
window seeing the same notes, and every window size from full screen down to a sticky note, light and dark."""
import asyncio, os, sys, json, subprocess, time
from playwright.async_api import async_playwright
HERE = os.path.dirname(os.path.abspath(__file__)); ROOT = os.path.dirname(HERE)
