URL = "http://localhost:8790/"
async def main():
    srv = subprocess.Popen([sys.executable, "-m", "http.server", "8790", "--bind", "127.0.0.1", "--directory", ROOT], stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL)
    time.sleep(0.8); ok = []
    def check(label, cond): ok.append(bool(cond)); print(("PASS " if cond else "FAIL ") + label)
