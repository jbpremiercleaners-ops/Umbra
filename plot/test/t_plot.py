            await A.click(".split .add-li"); await A.keyboard.type("Send floor plan"); await A.keyboard.press("Enter"); await A.keyboard.type("Ring the landlord")
            await A.keyboard.press("Enter"); await A.keyboard.type("Check parking")
            check("checklist: Enter makes the next line", await A.locator(".split .li").count() == 3)
            await A.keyboard.press("Home"); await A.keyboard.press("Backspace")
            check("checklist: Backspace at the start joins it to the line above", await A.input_value(".split .li >> nth=1 >> .li-t") == "Ring the landlordCheck parking")
            await A.fill(".split .li >> nth=1 >> .li-t", "Ring the landlord")
            await A.click(".split .li >> nth=0 >> .cbx"); await A.wait_for_timeout(150)
            check("ticked lines fold away", "1 ticked item" in await A.inner_text(".split .done-items summary"))
            await A.click(".split .ed-h button[aria-label=Pin]")
            await A.click(".split .ed-h button[aria-label=Colour]"); await A.click(".menu button[aria-label=Green]"); await A.wait_for_timeout(200)
            check("colour: the note turns green", await A.evaluate("document.querySelector('.split .ed').classList.contains('c-green')"))
            check("#viewing is a tag", "#viewing" in await A.inner_text(".split .ed-tags"))
            tb = await A.inner_text(".split .tblock")
            check("the title block says when it was edited, how much is ticked and how many words", "Edited" in tb and "1 of 2" in tb and "Words" in tb)
            await A.screenshot(path=OUT + "/01_notes.png")
            # folders
            await A.click(".k-sec button[aria-label='New folder']"); await A.fill(".dialog .field", "Leek Road"); await A.click(".dialog button:has-text('Create')"); await A.wait_for_timeout(300)
            check("a new folder, opened", (await A.inner_text(".bar-h")) == "Leek Road")
            await A.click(".k-row:has-text('All notes')"); await A.wait_for_timeout(200)
            await A.click(".list .row:has-text('Leek Road viewing')"); await A.wait_for_timeout(200)
            fid = await A.evaluate("P.folders[0].id")
            await A.select_option(".split .tb-sel", fid); await A.wait_for_timeout(500)
            await A.click(".k-row:has-text('Leek Road')"); await A.wait_for_timeout(200)
            check("the title block moves a note into a folder", await A.locator(".list .row").count() == 1)
            # a second note, search, tags
            await A.click(".k-row:has-text('All notes')"); await A.click(".bar .new"); await A.wait_for_timeout(100)
            await A.keyboard.type("Rates"); await A.keyboard.press("Enter"); await A.keyboard.type("Ask about small business relief #rates"); await A.wait_for_timeout(700)
            await A.click(".bar .new"); await A.wait_for_timeout(100); await A.click(".bar .new"); await A.wait_for_timeout(300)
            await A.click(".list .row:has-text('Rates')"); await A.wait_for_timeout(300)
            check("an empty note goes when you move on", await A.evaluate("[...P.notes.values()].filter(n => !n.deleted).length") == 2)
            await A.fill(".q", "landlord"); await A.wait_for_timeout(300)
            check("search finds words in checklists", await A.locator(".list .row").count() == 1)
            await A.fill(".q", ""); await A.wait_for_timeout(200)
            await A.click(".k-tags .tag:has-text('#rates')"); await A.wait_for_timeout(200)
            check("a tag filters", await A.locator(".list .row").count() == 1 and (await A.inner_text(".bar-h")) == "#rates")
            await A.click(".k-row:has-text('All notes')"); await A.wait_for_timeout(200)
            check("pinned first", (await A.inner_text(".grp >> nth=0 >> h4")) == "Pinned")
            # delete, undo, recently deleted
            await A.click(".list .row:has-text('Rates')"); await A.click(".split .ed-h button[aria-label=More]"); await A.click(".menu >> text=Delete"); await A.wait_for_timeout(300)
            check("deleted, with Undo", await A.locator(".list .row").count() == 1 and await A.locator(".toast button:has-text('Undo')").count() == 1)
            await A.click(".toast button:has-text('Undo')"); await A.wait_for_timeout(300)
            check("Undo puts it back", await A.locator(".list .row").count() == 2)
            await A.click(".list .row:has-text('Rates')"); await A.click(".split .ed-h button[aria-label=More]"); await A.click(".menu >> text=Delete"); await A.wait_for_timeout(300)
            await A.click(".k-row:has-text('Recently deleted')"); await A.wait_for_timeout(200)
            await A.click(".list .row"); await A.click(".split button:has-text('Put back')"); await A.wait_for_timeout(300)
            await A.click(".k-row:has-text('All notes')"); await A.wait_for_timeout(200)
            check("Recently deleted → Put back", await A.locator(".list .row").count() == 2)
            # Cards
            await A.click(".switch button:has-text('Cards')"); await A.wait_for_selector(".card")
            await A.click(".cap-b"); await A.keyboard.type("Chase solicitor about the lease"); await A.click(".cap button:has-text('Save')"); await A.wait_for_timeout(400)
            check("Take a note… saves a card", await A.locator(".card").count() == 3)
            await A.click(".card:has-text('Leek Road viewing') .c-list input >> nth=0"); await A.wait_for_timeout(300)
            check("ticking on the card", "2 ticked items" in await A.inner_text(".card:has-text('Leek Road viewing')"))
            await A.click(".card:has-text('Chase solicitor') .c-text"); await A.wait_for_selector(".pop.in")
            await A.click(".pop .ed-b"); await A.keyboard.press("End"); await A.keyboard.type(" on Monday")
            await A.screenshot(path=OUT + "/02_pop.png")
            await A.click(".pop button:has-text('Done')"); await A.wait_for_timeout(500)
            check("the pop-up saves into the card", "on Monday" in await A.inner_text(".card:has-text('Chase solicitor')"))
            await A.screenshot(path=OUT + "/03_cards.png")
            # Board
            await A.click(".switch button:has-text('Board')"); await A.wait_for_selector(".board .st"); await A.wait_for_timeout(400)
            check("the board: every note, waiting in the tray", await A.locator(".st").count() == 3 and await A.locator(".tray").count() == 1)
            spot = await A.evaluate("""(() => { const r = document.querySelector('.board').getBoundingClientRect();
              for (let y = r.top + 100; y < r.bottom - 80; y += 30) for (let x = r.left + 140; x < r.right - 240; x += 40) { const e = document.elementFromPoint(x, y); if (e && e.classList.contains('board')) return [x, y]; } return null; })()""")
            await A.mouse.dblclick(spot[0], spot[1]); await A.wait_for_selector(".st.editing textarea")
            await A.keyboard.type("Idea: split the unit"); await A.keyboard.press("Escape"); await A.wait_for_timeout(500)
            check("double-click adds a note you type straight onto", await A.locator(".st").count() == 4)
            idea = await A.evaluate("[...P.notes.values()].find(n => /split the unit/.test(n.body)).id")
            chase = await A.evaluate("[...P.notes.values()].find(n => /Chase solicitor/.test(n.body)).id")
            st = await A.locator(f".st[data-id='{chase}']").bounding_box()
            await A.mouse.move(st["x"] + st["width"] - 40, st["y"] + 20); await A.mouse.down(); await A.mouse.move(st["x"] + 200, st["y"] - 200, steps=8); await A.mouse.up(); await A.wait_for_timeout(500)
            check("a dragged note keeps its place", await A.evaluate(f"Number.isFinite(P.notes.get('{chase}').x)"))
            await A.keyboard.press("Escape"); await A.click(f".st[data-id='{idea}'] .st-in"); await A.wait_for_timeout(150)
            kb = await A.locator(f".st[data-id='{idea}'] .knob").bounding_box(); tb2 = await A.locator(f".st[data-id='{chase}']").bounding_box()
            await A.mouse.move(kb["x"] + 9, kb["y"] + 9); await A.mouse.down(); await A.mouse.move(tb2["x"] + 60, tb2["y"] + 40, steps=10); await A.mouse.up(); await A.wait_for_timeout(400)
            check("a dot dragged onto another note joins them with an arrow", await A.locator(".wire").count() == 1)
            await A.click(".tb:has-text('Frame')"); await A.wait_for_selector(".fr-in"); await A.fill(".fr-in", "Leek Road deal"); await A.keyboard.press("Enter"); await A.wait_for_timeout(300)
            check("a frame, drawn as a red line and named", "Leek Road deal" in await A.inner_text(".fr"))
            fb = await A.locator(".fr").bounding_box(); ib = await A.locator(f".st[data-id='{idea}']").bounding_box()
            await A.keyboard.press("Escape")
            await A.mouse.move(ib["x"] + ib["width"] - 30, ib["y"] + 14); await A.mouse.down(); await A.mouse.move(fb["x"] + 300, fb["y"] + 60, steps=8); await A.mouse.up(); await A.wait_for_timeout(300)
            before = await A.evaluate(f"[P.notes.get('{idea}').x, P.notes.get('{idea}').y]")
            await A.keyboard.press("Escape")
            ft = await A.locator(".fr-t").bounding_box()
            await A.mouse.move(ft["x"] + 20, ft["y"] + 8); await A.mouse.down(); await A.mouse.move(ft["x"] + 120, ft["y"] + 68, steps=8); await A.mouse.up(); await A.wait_for_timeout(500)
            after = await A.evaluate(f"[P.notes.get('{idea}').x, P.notes.get('{idea}').y]")
            check("moving the frame carries the notes inside it", after[0] - before[0] > 50 and after[1] - before[1] > 20)
            z0 = await A.inner_text(".zl"); await A.click(".b-zoom button[aria-label='Zoom in']"); check("zoom", z0 != await A.inner_text(".zl"))
            await A.click(".tb:has-text('Fit')"); await A.wait_for_timeout(300)
            await A.screenshot(path=OUT + "/04_board.png")
            # Today
            await A.evaluate("""(async () => { const y = new Date(Date.now() - 864e5); const n = newNote({ title: 'Yesterday', daily: dayKey(y), items: [{ id: 'a', t: 'Chase the surveyor', done: false }, { id: 'b', t: 'Done already', done: true }] }); await save(n); })()""")
            await A.click(".switch button:has-text('Notes')"); await A.wait_for_selector(".split")
            await A.click(".bar .today"); await A.wait_for_timeout(500)
            its = await A.evaluate("Array.from(document.querySelectorAll('.split .li .li-t')).map(i => i.value)")
            check("Today: last time's unticked lines carried over, not the ticked ones", "Chase the surveyor" in its and "Done already" not in its)
            await A.click(".bar .today"); await A.wait_for_timeout(300)
            check("Today again opens the same page", await A.evaluate("[...P.notes.values()].filter(n => n.daily === dayKey(new Date())).length") == 1)
            # kept after a reload, and offline
            await A.wait_for_function("P.timers.size === 0", timeout=5000)
            n0 = await A.evaluate("P.notes.size")
            await A.reload(); await A.wait_for_selector(".key"); await A.wait_for_timeout(500)
            check("everything's still there after closing and opening", await A.evaluate("P.notes.size") == n0 and await A.evaluate("P.folders.length") == 1)
            await A.wait_for_function("navigator.serviceWorker && navigator.serviceWorker.controller !== null", timeout=10000)
            await c.set_offline(True); await A.reload(); await A.wait_for_selector(".key", timeout=10000)
            check("works offline", await A.evaluate("P.notes.size") == n0)
            await c.set_offline(False)
            # a second window on the same device
            B = await c.new_page(); await B.goto(URL); await B.wait_for_selector(".key")
            await A.click(".bar .new"); await A.wait_for_timeout(100); await A.keyboard.type("From the first window"); await A.wait_for_timeout(900)
            await B.wait_for_function("[...P.notes.values()].some(n => n.title === 'From the first window')", timeout=5000)
            check("another Plot window on this device sees the note", True)
            await B.close()
            # back up and restore
            await A.click(".k-foot .k-row:has-text('Settings')"); await A.wait_for_selector(".dialog")
            async with A.expect_download() as dl: await A.click(".dialog button:has-text('Back up notes')")
            d = await dl.value; path = os.path.join(OUT, "backup.json"); await d.save_as(path)
            data = json.load(open(path))
            check("back-up: a file with every note and folder", data["app"] == "Plot" and len(data["notes"]) == n0 + 1 and len(data["folders"]) == 1)
            await A.keyboard.press("Escape")
            await A.evaluate("(async () => { for (const n of [...P.notes.values()]) await destroy(n.id); render(); })()")
            check("(wiped)", await A.evaluate("P.notes.size") == 0)
            await A.click(".k-foot .k-row:has-text('Settings')"); await A.wait_for_selector(".dialog")
            await A.set_input_files(".dialog input[type=file]", path); await A.wait_for_timeout(800)
            check("restore puts them all back", await A.evaluate("P.notes.size") == n0 + 1)
            await A.screenshot(path=OUT + "/05_after_restore.png")
